"""Demo library builder (SPEC §14 "Demo mode").

Reads ``demo_files.txt`` and creates deterministic files under ``<data_dir>/demo/incoming``:
content is a SHAKE-256 stream seeded by the manifest path (so CRCs are stable across runs and
machines), sized from the manifest, and ``{crc32}`` in a name is replaced with the real CRC32 of
that content. Library folders are created under ``<data_dir>/demo/library/{Movies,TV,Anime}``.
"""

from __future__ import annotations

import hashlib
import shutil
import zlib
from dataclasses import dataclass
from pathlib import Path

from schema_app.domain import MediaKind

MANIFEST = Path(__file__).with_name("demo_files.txt")
MARKER = ".schema-demo"
LIBRARY_FOLDERS = {MediaKind.MOVIE: "Movies", MediaKind.SERIES: "TV", MediaKind.ANIME: "Anime"}
CRC_TOKEN = "{crc32}"


@dataclass(frozen=True)
class DemoEntry:
    path: str  # relative, "/"-separated, may contain {crc32}
    size_kib: int
    expectation: str


@dataclass(frozen=True)
class DemoLayout:
    root: Path
    incoming: Path
    library: Path
    library_roots: dict[MediaKind, Path]


def read_manifest(path: Path = MANIFEST) -> list[DemoEntry]:
    entries: list[DemoEntry] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 2:
            continue
        try:
            size = int(parts[1])
        except ValueError:
            continue
        entries.append(DemoEntry(path=parts[0], size_kib=max(0, size), expectation=parts[2] if len(parts) > 2 else ""))
    return entries


def demo_content(entry: DemoEntry) -> bytes:
    """Deterministic pseudo-random bytes for one manifest entry."""
    return hashlib.shake_256(f"schema-demo:{entry.path}".encode()).digest(entry.size_kib * 1024)


def resolved_name(entry: DemoEntry, content: bytes) -> str:
    if CRC_TOKEN not in entry.path:
        return entry.path
    crc = f"{zlib.crc32(content) & 0xFFFFFFFF:08X}"
    return entry.path.replace(CRC_TOKEN, crc)


def layout(root: Path) -> DemoLayout:
    library = root / "library"
    return DemoLayout(
        root=root,
        incoming=root / "incoming",
        library=library,
        library_roots={kind: library / name for kind, name in LIBRARY_FOLDERS.items()},
    )


def build(root: Path, *, manifest: Path = MANIFEST, wipe: bool = False) -> tuple[DemoLayout, list[Path]]:
    """Create the incoming files and empty library folders. ``wipe`` removes ``root`` first."""
    root = Path(root)
    if wipe and root.exists():
        if not (root / MARKER).exists() and any(root.iterdir()):
            raise RuntimeError(f"refusing to wipe {root}: it is not a Schema demo folder")
        shutil.rmtree(root)
    demo = layout(root)
    demo.incoming.mkdir(parents=True, exist_ok=True)
    for folder in demo.library_roots.values():
        folder.mkdir(parents=True, exist_ok=True)
    (root / MARKER).write_text("Generated by Schema demo mode; safe to delete.\n", encoding="utf-8")
    created: list[Path] = []
    for entry in read_manifest(manifest):
        content = demo_content(entry)
        target = demo.incoming.joinpath(*resolved_name(entry, content).split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        created.append(target)
    return demo, created


def is_built(root: Path) -> bool:
    return (Path(root) / MARKER).exists() and (Path(root) / "incoming").is_dir()
